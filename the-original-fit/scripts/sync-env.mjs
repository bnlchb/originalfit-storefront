#!/usr/bin/env node
/**
 * Generates `src/js/env.js` from `.env` for static deployments
 * (GitHub Pages, Netlify, S3, …) where no .env endpoint exists.
 * Run:  npm run env:sync
 */
import { readFile, writeFile, existsSync } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const ENV_FILE = join(ROOT, '.env');
const OUT_FILE = join(ROOT, 'src', 'js', 'env.js');

const PLACEHOLDERS = ['', 'your_supabase_project_url', 'your_supabase_anon_key'];

function readEnv(text) {
  const out = {};
  for (const line of text.split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (!m) continue;
    out[m[1]] = m[2].replace(/^["']|["']$/g, '').trim();
  }
  return out;
}

async function main() {
  let env = {};
  if (existsSync(ENV_FILE)) env = readEnv(await.readFile(ENV_FILE, 'utf8'));

  const url = PLACEHOLDERS.includes(env.SUPABASE_URL) ? '' : env.SUPABASE_URL;
  const key = PLACEHOLDERS.includes(env.SUPABASE_ANON_KEY) ? '' : env.SUPABASE_ANON_KEY;

  const banner = `/* Auto-generated by \`npm run env:sync\` from .env — gitignored, never commit. */\n`;
  const body = `window.TOF_ENV = { SUPABASE_URL: ${JSON.stringify(url)}, SUPABASE_ANON_KEY: ${JSON.stringify(key)} };\n`;

  await writeFile(OUT_FILE, banner + body, 'utf8');
  console.log(url && key
    ? '✓ src/js/env.js written — Supabase credentials synced.'
    : 'i src/js/env.js written with empty values (fill .env, then re-run `npm run env:sync`).');
}

main().catch(err => { console.error(err); process.exit(1); });
