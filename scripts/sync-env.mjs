#!/usr/bin/env node
/**
 * Generates `src/js/env.js` from `.env` for static deployments
 * (GitHub Pages, Netlify, S3, …) where no .env endpoint exists.
 * Run:  npm run env:sync
 */
import { readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const ENV_FILE = join(ROOT, '.env');
const OUT_FILE = join(ROOT, 'src', 'js', 'env.js');

const PLACEHOLDERS = ['', 'your_supabase_project_url', 'your_supabase_anon_key'];

function readEnv(text) {
  const out = {};
  for (const line of text.split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (!m) continue;
    out[m[1]] = m[2].replace(/^["']|["']$/g, '').trim();
  }
  return out;
}

async function main() {
  let env = {};
  if (existsSync(ENV_FILE)) env = readEnv(await readFile(ENV_FILE, 'utf8'));

  // Deploy-time injection wins: the GitHub Actions workflow passes
  // SUPABASE_URL / SUPABASE_ANON_KEY as repository *secrets* (never committed).
  // Locally, the values come straight from .env — no hard-coded fallback anywhere.
  const rawUrl = process.env.SUPABASE_URL || env.SUPABASE_URL || '';
  const rawKey = process.env.SUPABASE_ANON_KEY || env.SUPABASE_ANON_KEY || '';

  const url = PLACEHOLDERS.includes(rawUrl) ? '' : rawUrl;
  const key = PLACEHOLDERS.includes(rawKey) ? '' : rawKey;

  const banner = '/* Auto-generated by `npm run env:sync` — from .env (local) or deploy secrets (CI). */\n'
    + '/* Credentials live ONLY in .env / deploy secrets; this file is git-ignored and regenerated at build time. */\n';
  const body = `window.TOF_ENV = { SUPABASE_URL: ${JSON.stringify(url)}, SUPABASE_ANON_KEY: ${JSON.stringify(key)} };\n`;

  await writeFile(OUT_FILE, banner + body, 'utf8');
  console.log(url && key
    ? '✓ src/js/env.js written — Supabase credentials synced from the environment.'
    : 'i src/js/env.js written with empty values (fill .env, then re-run `npm run env:sync`).');

  // Legacy v1 storefront (root files are local-only and untracked): refresh its
  // constants when present so no credentials stay hard-coded in the workspace.
  const LEGACY_CONFIG = join(ROOT, '..', 'config.js');
  if (existsSync(LEGACY_CONFIG)) {
    try {
      const legacy = await readFile(LEGACY_CONFIG, 'utf8');
      const next = legacy
        .replace(/(const\s+SUPABASE_URL\s*=\s*')[^']*(')/, `$1${url}$2`)
        .replace(/(const\s+SUPABASE_ANON_KEY\s*=\s*')[^']*(')/, `$1${key}$2`);
      if (next !== legacy) {
        await writeFile(LEGACY_CONFIG, next, 'utf8');
        console.log('✓ legacy ../config.js refreshed from the same environment.');
      }
    } catch { /* legacy file is optional — never block the main sync */ }
  }
}

main().catch(err => { console.error(err); process.exit(1); });
